    Result<void> acknowledge(hid_device* handle, const std::array<uint8_t, 64>& request) const
    {
        auto response = query(handle, request);
        if (!response)
            return response.error();
        if (*response != 0)
            return DeviceError::protocolError("Kraken V4 setting acknowledgment differs from capture");
        return {};
    }

