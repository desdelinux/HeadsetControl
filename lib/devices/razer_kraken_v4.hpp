    Result<BatteryResult> getBattery(hid_device* handle) override
    {
        auto charging = query(handle, CHARGING_QUERY);
        if (!charging)
            return charging.error();
        if (*charging > 1)
            return DeviceError::protocolError("Invalid Kraken V4 charging state");

        auto level = query(handle, BATTERY_QUERY);
        if (!level)
            return level.error();
        if (*level > 100)
            return DeviceError::protocolError("Invalid Kraken V4 battery percentage");

        return BatteryResult {
            .level_percent = *level,
            .status        = *charging ? BATTERY_CHARGING : BATTERY_AVAILABLE
        };
    }

    Result<SidetoneResult> setSidetone(hid_device* handle, uint8_t level) override
    {
        if (level > 128)
            return DeviceError::protocolError("Kraken V4 sidetone must be between 0 and 128");

        // Quantize to the finite native levels observed in Synapse, selecting
        // complete captured packets. Positive requests keep monitoring enabled.
        const uint8_t native = level ? std::max(1, level * 15 / 128) : 0;
        const uint8_t actual = level ? (native * 128 + 14) / 15 : 0;
        if (auto result = acknowledge(handle, actual ? SIDETONE_ON : SIDETONE_OFF); !result) {
            if (actual) {
                auto restored = acknowledge(handle, SIDETONE_OFF);
                if (!restored)
                    return restored.error();
            }
            return result.error();
        }

        if (actual) {
            auto result = acknowledge(handle, SIDETONE_LEVELS[native]);
            if (!result) {
                // ON may have succeeded. Restore OFF with its captured packet.
                auto restored = acknowledge(handle, SIDETONE_OFF);
                if (!restored)
                    return restored.error();
                return result.error();
            }
        }

        return SidetoneResult {
            .current_level = actual,
            .min_level     = 0,
            .max_level     = 128,
            .device_min    = 0,
            .device_max    = 15,
            .is_muted      = actual == 0,
            .device_level  = native,
            .level_name    = actual ? "captured discrete level" : "off"
        };
    }

    Result<LightsResult> setLights(hid_device* handle, bool on) override
    {
        // ON uses the captured Synapse 25% brightness, not an inferred range.
        if (auto result = acknowledge(handle, on ? LIGHTS_ON : LIGHTS_OFF); !result)
            return result.error();
        return LightsResult { .enabled = on, .mode = on ? "25% brightness" : "off" };
    }

